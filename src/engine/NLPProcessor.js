const NEGATION_WORDS = ['no ', 'not ', 'without ', "don't have", "don't feel", 'no sign', 'never had']
const DURATION_PATTERNS = [
  {pattern:/(\d+)\s*day/i,unit:'days'},{pattern:/(\d+)\s*hour/i,unit:'hours'},
  {pattern:/(\d+)\s*week/i,unit:'weeks'},{pattern:/since yesterday/i,fixed:'~24 hours'},
  {pattern:/since morning/i,fixed:'~8 hours'},{pattern:/few days/i,fixed:'~3 days'},
  {pattern:/long time/i,fixed:'chronic'},{pattern:/always/i,fixed:'chronic'},
  {pattern:/years/i,fixed:'chronic'},{pattern:/months/i,fixed:'chronic'},
  {pattern:/just started/i,fixed:'<1 hour'},{pattern:/sudden/i,fixed:'sudden onset'},
  {pattern:/this morning/i,fixed:'~4 hours'},{pattern:/last night/i,fixed:'~12 hours'},
  {pattern:/since last week/i,fixed:'~7 days'},{pattern:/for a while/i,fixed:'several days'},
]
const SEVERITY_WORDS = {
  'mild':2,'slight':2,'little':2,'moderate':5,'bad':7,'terrible':8,'awful':8,
  'severe':8,'very bad':8,'really bad':8,'excruciating':10,'unbearable':10,
  'worst':10,'killing me':9,'killing':9,
}

export function processText(text) {
  const lower = text.toLowerCase()
  const result = { raw:text, symptoms:[], severity_override:null, duration:null, negated:[], tags:[] }

  for (const dp of DURATION_PATTERNS) {
    const m = lower.match(dp.pattern)
    if (m) { result.duration = dp.fixed || `${m[1]} ${dp.unit}`; break }
  }
  for (const [word, val] of Object.entries(SEVERITY_WORDS)) {
    if (lower.includes(word)) { result.severity_override = val; break }
  }

  const negatedPhrases = []
  for (const neg of NEGATION_WORDS) {
    const idx = lower.indexOf(neg)
    if (idx !== -1) negatedPhrases.push(lower.substring(idx + neg.length, idx + neg.length + 40))
  }

  const found = new Set()
  // Sort by phrase length descending so longer/more-specific phrases match first
  const entries = Object.entries(SYMPTOM_MAP).sort((a, b) => b[0].length - a[0].length)
  for (const [phrase, sd] of entries) {
    if (!lower.includes(phrase)) continue
    const isNegated = negatedPhrases.some(np => np.includes(phrase) || phrase.includes(np.split(' ')[0]))
    if (isNegated) { result.negated.push(sd.key); continue }
    if (!found.has(sd.key)) {
      found.add(sd.key)
      const sev = result.severity_override || sd.severity_hint || 5
      result.symptoms.push({ key:sd.key, severity:Math.min(10,sev), tag:sd.tag||null, phrase_matched:phrase })
      if (sd.tag) result.tags.push(sd.tag)
    }
  }

  // ── Compositional inference: body-part + trouble phrases ───
  const BODY_TROUBLE = [
    { body: 'chest', verbs: ['giving me','disturbing','trouble','problem','issue','not good'], key: 'chest_pain', hint: 6 },
    { body: 'stomach', verbs: ['giving me','disturbing','trouble','problem','issue','not good','running'], key: 'abdominal_pain', hint: 5 },
    { body: 'head', verbs: ['giving me','disturbing','trouble','problem','issue','not good'], key: 'headache', hint: 5 },
    { body: 'back', verbs: ['giving me','disturbing','trouble','problem','issue'], key: 'back_pain', hint: 5 },
    { body: 'waist', verbs: ['giving me','disturbing','trouble','problem','issue'], key: 'back_pain', hint: 5 },
    { body: 'eye', verbs: ['disturbing','trouble','problem','issue','not good','giving me'], key: 'eye_pain', hint: 5 },
    { body: 'leg', verbs: ['giving me','disturbing','trouble','weak','swollen'], key: 'oedema', hint: 5 },
  ]
  for (const { body, verbs, key, hint } of BODY_TROUBLE) {
    if (!lower.includes(body)) continue
    if (verbs.some(v => lower.includes(v)) && !found.has(key)) {
      found.add(key)
      result.symptoms.push({ key, severity: result.severity_override || hint, tag: null, phrase_matched: `[composed: ${body}+verb]` })
    }
  }

  return result
}

export function detectEmotion(text) {
  const l = text.toLowerCase()
  if (l.includes('scared') || l.includes('afraid') || l.includes('worried') || l.includes('fear')) return 'anxious'
  if (l.includes('terrible') || l.includes('horrible') || l.includes('suffering')) return 'distressed'
  if (l.includes('confused') || l.includes("don't understand")) return 'confused'
  if (l.includes('thank') || l.includes('helped')) return 'grateful'
  if (l.includes('hopeless') || l.includes('burden') || l.includes('dark thoughts')) return 'distressed'
  return 'neutral'
}

