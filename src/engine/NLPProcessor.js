export const LUGANDA_SEVERITY_WORDS = {
  'peefu': 3, 'butiiti': 3, 'mangu': 5,
  'ennyo': 7, 'nnyingi': 7, 'omuwendo omukulu': 8,
  'obuzibu obunafu': 8, 'situukirira': 9, 'ekibi nnyo': 9,
}

export function processTextMultilingual(text, lang = 'en') {
  const baseResult = processText(text)
  if (lang !== 'lg') return baseResult

  const lower = text.toLowerCase()
  const found = new Set(baseResult.symptoms.map(s => s.key))

  if (!baseResult.duration) {
    for (const dp of LUGANDA_DURATION_PATTERNS) {
      const m = lower.match(dp.pattern)
      if (m) { baseResult.duration = dp.fixed || (m[1] + ' ' + dp.unit); break }
    }
  }
  if (!baseResult.severity_override) {
    for (const [word, val] of Object.entries(LUGANDA_SEVERITY_WORDS)) {
      if (lower.includes(word)) { baseResult.severity_override = val; break }
    }
  }
  for (const [phrase, sd] of Object.entries(LUGANDA_SYMPTOMS)) {
    if (!lower.includes(phrase)) continue
    if (!found.has(sd.key)) {
      found.add(sd.key)
      const sev = baseResult.severity_override || sd.severity_hint || 5
      baseResult.symptoms.push({ key: sd.key, severity: Math.min(10, sev), tag: sd.tag || null, phrase_matched: phrase })
    }
  }
  return baseResult
}
